"""Browser regression check. Start Vite on port 4173 first."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).parent
with sync_playwright() as pw:
    browser=pw.chromium.launch(args=['--no-sandbox','--enable-unsafe-swiftshader'])
    page=browser.new_page(viewport={'width':1440,'height':1100})
    page.set_default_timeout(10000)
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(os.environ.get('PROTOTYPE_URL','http://127.0.0.1:4173'))
    expect(page.locator('.thumb img')).to_have_count(2)
    page.locator('#search').fill('#workshop + PLA')
    expect(page.locator('.part-card')).to_have_count(1)
    card=page.locator('.part-card').first
    expect(card.locator('.part-identity')).to_contain_text('Part number')
    page.locator('#search').fill('#workshop')
    page.locator('[data-card-version="7382-4916"]').select_option('001')
    expect(card.locator('.card-context')).to_contain_text('3MF E')
    expect(card.locator('.card-details')).to_contain_text('46 g')
    expect(card.locator('.file-pills')).not_to_contain_text('G')
    page.locator('[data-card-version="7382-4916"]').select_option('003')
    page.locator('#search').fill('')
    page.locator('#search').blur()
    page.screenshot(path=str(ROOT/'screenshots/library.png'),full_page=True)
    page.locator('[data-open="7382-4916"]').first.click()
    expect(page.locator('#viewer canvas')).to_have_count(1)
    expect(page.locator('#part-version')).to_have_value('003')
    page.locator('[data-action="bounds"]').click()
    expect(page.locator('#dimensions')).to_be_visible()
    page.locator('[data-action="bounds"]').click()
    expect(page.locator('[data-tab="details"]')).to_have_text('Part Details')
    expect(page.locator('.detail-metrics')).to_contain_text('0.2 mm')
    expect(page.locator('.detail-metrics')).to_contain_text('15%')
    expect(page.locator('.detail-metrics')).to_contain_text('grid')
    expect(page.locator('.detail-metric').filter(has_text='Total weight').locator('dd')).to_have_text('Unknown')
    expect(page.locator('.detail-metric').filter(has_text='Print time').locator('dd')).to_have_text('Slice required')
    expect(page.locator('.detail-metric').filter(has_text='Plates in 3MF').locator('dd')).to_have_text('2')
    expect(page.locator('.filament-card')).to_have_count(1)
    expect(page.locator('.filament-card').last).to_contain_text('#DCF478')
    expect(page.locator('.filament-card')).to_contain_text('Generic PLA')
    expect(page.locator('.filament-panel')).not_to_contain_text('#FFFFFF')
    page.locator('[data-action="time-help"]').click()
    expect(page.locator('dialog')).to_contain_text('Slice all plates')
    page.locator('#close-modal').click()
    page.evaluate('window.scrollTo(0, 0)')
    page.screenshot(path=str(ROOT/'screenshots/part-details.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile Part Details overflow'
    page.screenshot(path=str(ROOT/'screenshots/part-details-mobile.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':1100})
    page.locator('#part-version').select_option('002')
    expect(page.locator('.filament-card')).to_have_count(0)
    expect(page.locator('.detail-metric').filter(has_text='Layer height').locator('dd')).to_have_text('Unknown')
    page.locator('#part-version').select_option('003')
    page.screenshot(path=str(ROOT/'screenshots/part.png'),full_page=True)
    page.locator('[data-file="stl"]').click()
    expect(page.locator('[data-tab="where"]')).to_have_attribute('aria-selected','true')
    expect(page.locator('.graph-node')).to_have_count(4)
    expect(page.locator('.graph-line')).to_have_count(3)
    expect(page.locator('.graph-node.selected')).to_contain_text('STL · Rev C')
    page.screenshot(path=str(ROOT/'screenshots/where-used.png'),full_page=True)
    page.locator('[data-action="change"]').click()
    page.locator('[data-action="confirm-change"]').click()
    expect(page.locator('#form-error')).to_contain_text('Select at least one')
    page.locator('[data-change-file="project"]').check()
    page.locator('[data-file-comment="project"]').fill('Tune supports for PLA. Reduced contact area.')
    page.locator('#change-material').select_option('PLA')
    page.locator('[data-action="confirm-change"]').click()
    expect(page.locator('#part-version')).to_have_value('004')
    expect(page.locator('.baseline .version').last).to_have_text('H')
    expect(page.locator('.commit-summary').first).to_contain_text('Tune supports for PLA.')
    expect(page.locator('#log-004')).to_contain_text('Unchanged from previous Part version.')
    expect(page.locator('#log-004')).to_contain_text('Reduced contact area.')
    page.locator('#toast').evaluate('(el)=>el.style.display="none"')
    page.screenshot(path=str(ROOT/'screenshots/logbook.png'),full_page=True)
    page.locator('[data-tab="details"]').click()
    expect(page.locator('.filament-card')).to_have_count(0)
    expect(page.locator('.details-scope')).to_have_text('Metadata unavailable')
    page.locator('[data-tab="reports"]').click()
    page.locator('[data-action="report"]').click()
    page.locator('#outcome').select_option('Failed')
    page.locator('#notes').fill('<script>unsafe</script> Fit was too tight.')
    page.locator('#photo-upload').set_input_files(str(ROOT/'screenshots/library.png'))
    expect(page.locator('#photo-preview img')).to_have_count(1)
    page.locator('[data-action="save-report"]').click()
    expect(page.locator('#part-version option')).to_have_count(4)
    expect(page.locator('#part-version')).to_have_value('004')
    page.locator('[data-report-open="PR-002"]').click()
    expect(page.locator('dialog')).to_contain_text('<script>unsafe</script>')
    expect(page.locator('dialog script')).to_have_count(0)
    page.locator('#close-modal').click()
    page.locator('[data-tab="attachments"]').click()
    page.locator('[data-action="attach"]').click()
    page.locator('#attachment-file').set_input_files({'name':'assembly-guide.txt','mimeType':'text/plain','buffer':b'Fit the mount with two screws.'})
    page.locator('[data-action="save-attachment"]').click()
    expect(page.locator('.attachment-row')).to_have_count(1)
    with page.expect_download() as download:
        page.locator('[download="assembly-guide.txt"]').click()
    assert download.value.suggested_filename=='assembly-guide.txt'
    page.locator('[data-action="git-link"]').click()
    page.locator('#git-url').fill('javascript:alert(1)')
    page.locator('#git-ref').fill('main')
    page.locator('[data-action="save-git"]').click()
    expect(page.locator('#form-error')).to_contain_text('HTTP(S)')
    page.locator('#git-name').fill('Controller firmware')
    page.locator('#git-url').fill('https://github.com/example/firmware')
    page.locator('#git-ref').fill('a'*40)
    page.locator('[data-action="save-git"]').click()
    expect(page.locator('.attachment-row')).to_have_count(2)
    expect(page.locator('.attachment-list')).to_contain_text('Commit:')
    expect(page.locator('#part-version option')).to_have_count(4)
    page.locator('#toast').evaluate('(el)=>el.style.display="none"')
    page.screenshot(path=str(ROOT/'screenshots/attachments.png'),full_page=True)
    page.locator('#part-version').select_option('003')
    expect(page.locator('.attachment-row')).to_have_count(0)
    page.locator('[data-tab="reports"]').click()
    expect(page.locator('[data-report-open="PR-002"]')).to_have_count(0)
    expect(page.locator('[data-report-open="PR-001"]')).to_have_count(1)
    page.locator('[data-page="library"]').first.click()
    card=page.locator('.part-card').filter(has_text='7382-4916')
    expect(card.locator('.card-context')).to_contain_text('3MF G')
    expect(card.locator('.card-details')).to_contain_text('PLA')
    page.locator('[data-page="import"]').click()
    page.locator('#stl-upload').set_input_files(str(ROOT/'assets/keychain.stl'))
    expect(page.locator('#part-version')).to_have_value('001')
    page.locator('[data-file="stl"]').click()
    expect(page.locator('.relation-diagram')).to_contain_text('CAD source unknown')
    expect(page.locator('.graph-line')).to_have_count(0)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile detail overflow'
    page.locator('[data-action="menu"]').click()
    page.locator('[data-page="library"]').first.click()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile library overflow'
    page.locator('#toast').evaluate('(el)=>el.style.display="none"')
    page.screenshot(path=str(ROOT/'screenshots/mobile.png'),full_page=True)
    assert not errors,errors
    browser.close()
print('PASS: version-specific cards, diagram, file-change registration, immutable history, logbook, reports, attachments/download/Git, isolation, STL import, mobile, no JS errors.')
