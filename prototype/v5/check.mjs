import {chromium} from '../../MVP/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const here=path.dirname(fileURLToPath(import.meta.url));
const out=path.resolve(here,'../screenshots/v5');fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(here,'../Printchill-demo-v5.html')).href);
  await page.waitForFunction(()=>document.querySelectorAll('.part-card .preview img[src]').length===5);
  await page.getByRole('button',{name:'Create collection',exact:true}).click();
  await page.locator('#new-group').fill('Bike accessories');await page.locator('#modal-submit').click();
  await page.screenshot({path:path.join(out,'01-library.png'),fullPage:true});
  await page.getByRole('button',{name:'Table view',exact:true}).click();
  assert.equal(await page.locator('tbody tr').count(),5);
  await page.screenshot({path:path.join(out,'02-table.png'),fullPage:true});
  await page.getByRole('button',{name:'Card view',exact:true}).click();
  await page.locator('.part-card').filter({hasText:'Zadel'}).click();
  await page.locator('#viewer canvas').waitFor();
  await page.getByRole('button',{name:'Edit collections',exact:true}).click();
  await page.getByLabel('Bike accessories',{exact:true}).check();await page.locator('#modal-submit').click();
  assert.match(await page.locator('.part-metadata').innerText(),/Collected by:[\s\S]*Bike accessories/);
  assert.ok(await page.getByRole('button',{name:'Open in Bambu Studio',exact:true}).locator('img').evaluate(img=>img.complete&&img.naturalWidth>0));
  assert.ok(await page.getByRole('button',{name:'Open in SolidWorks',exact:true}).locator('img').evaluate(img=>img.complete&&img.naturalWidth>0));
  await page.getByRole('button',{name:'Open in SolidWorks',exact:true}).click();
  await page.getByRole('heading',{name:'Open in SolidWorks',exact:true}).waitFor();
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('tab',{name:'Wiki',exact:true}).click();
  await page.getByRole('heading',{name:'Part wiki',exact:true}).waitFor();
  await page.getByRole('tab',{name:'Part details',exact:true}).click();
  await page.getByText('Created on',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Dimensions',exact:true}).click();
  await page.screenshot({path:path.join(out,'03-part-details.png'),fullPage:true});
  await page.getByRole('tab',{name:'Print plates',exact:true}).click();
  await page.locator('.plate-large').waitFor();
  await page.screenshot({path:path.join(out,'04-print-plates.png'),fullPage:true});
  await page.getByRole('tab',{name:'History',exact:true}).click();
  await page.getByRole('button',{name:'Save as / derive',exact:true}).click();
  await page.locator('#derived-name').fill('Zadelbuis klem — alternative clearance');
  const derivedNumber=await page.locator('#derived-number').inputValue();
  await page.getByRole('button',{name:'Create derived Part',exact:true}).click();
  await page.locator('[data-branch="'+derivedNumber+'"]').waitFor();
  await page.screenshot({path:path.join(out,'05-history.png'),fullPage:true});
  await page.locator('[data-branch="'+derivedNumber+'"]').click();
  assert.match(await page.locator('h1').innerText(),new RegExp(derivedNumber));
  await page.locator('.origin-link [data-branch]').click();
  await page.getByRole('tab',{name:'Print reports',exact:true}).click();
  await page.getByRole('button',{name:'Record attempt'}).click();
  await page.locator('#printer').fill('Bambu Lab X1 Carbon');
  await page.locator('#measurements').fill('Bore · 20.0 mm expected · 19.8 mm measured · −0.2 mm');
  await page.locator('#notes').fill('Fit is close. Review clearance before the next print.');
  await page.screenshot({path:path.join(out,'06-print-report.png'),fullPage:true});
  await page.getByRole('button',{name:'Save print report',exact:true}).click();
  await page.getByText('Fit is close.',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Settings',exact:false}).click();
  await page.getByRole('button',{name:'Open backup & restore',exact:false}).click();
  await page.getByRole('button',{name:'Use a sample backup',exact:false}).click();
  await page.getByRole('button',{name:'Confirm restore',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'07-backup-preview.png'),fullPage:true});
  await page.getByRole('button',{name:'Part library',exact:false}).click();
  await page.setViewportSize({width:1366,height:768});
  await page.screenshot({path:path.join(out,'08-laptop.png'),fullPage:true});
  const width=await page.locator('#sidebar').evaluate(el=>el.getBoundingClientRect().width);
  assert.ok(width/1366>=.19&&width/1366<=.21);
  const heights=await page.locator('.part-card').evaluateAll(cards=>cards.map(c=>c.getBoundingClientRect().height));
  assert.ok(Math.max(...heights)-Math.min(...heights)<2);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(out,'09-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('V5 passed: standalone file, 5 real geometries, table, dimensions, plates, history, saved demo report, backup review, laptop and mobile.');
}finally{await browser.close();}
