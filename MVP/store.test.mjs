import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {Workspace,restore} from './store.mjs';
const samples=fileURLToPath(new URL('../POC material/',import.meta.url));
test('UC-018: immutable versions, repeated saves, restart, report and verified restore',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'prc-test-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const dir=path.join(root,'workspace'),original=path.join(samples,'27980400_wall_mount_rev_A.3mf');
  let w=new Workspace(dir);
  const part=w.importPart('Wall mount',[original,path.join(samples,'27980400_wall_mount_rev_A.STL')]);
  const j=w.work(part,1),file=w.workPath(j);
  w.report(part,1,'Success','Initial print');
  fs.writeFileSync(file,'incomplete');
  assert.throws(()=>w.confirm(j.id,1));assert.equal(w.state().versions.length,1);
  fs.copyFileSync(path.join(samples,'98056723_A_WTW_valve.3mf'),file);
  assert.equal(w.state().jobs[0].changed,true);
  assert.equal(w.confirm(j.id,1),2);assert.equal(w.confirm(j.id,2),2);
  assert.deepEqual(w.files(part,2).STL,w.files(part,1).STL);
  fs.copyFileSync(original,file);w.db.close();w=new Workspace(dir);
  assert.equal(w.state().jobs[0].changed,true);assert.equal(w.state().jobs[0].base,2);
  const backup=path.join(root,'backup'),restored=path.join(root,'restored');
  w.backup(backup);w.db.close();fs.mkdirSync(restored);
  const existing=path.join(restored,'existing.txt');fs.writeFileSync(existing,'keep');
  const actual=restore(backup,restored);assert.equal(path.dirname(actual),restored);
  assert.equal(fs.readFileSync(existing,'utf8'),'keep');w=new Workspace(actual);
  assert.equal(w.state().reports[0].v,1);assert.equal(w.state().jobs.length,0);
  assert.deepEqual(fs.readFileSync(w.object(w.files(part,1)['3MF'].key)),fs.readFileSync(original));w.db.close();
});
