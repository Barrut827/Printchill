import {test} from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
import {Workspace} from './store.mjs';
test('UC-006/008: browse sample, inspect geometry, save search, preview restore',async t=>{
  const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'prc-ui-'));
  const root=path.join(tmp,'workspace'),w=new Workspace(root),samples=fileURLToPath(new URL('../POC material/',import.meta.url));
  const target=w.importPart('Wall mount',['27980400_wall_mount_rev_A.STL','7382-4916 - makita blower wall mount.3mf'].map(n=>path.join(samples,n)));
  w.run('INSERT INTO part_tags VALUES(?,?)',target,'fixture');
  for(let i=0;i<18;i++)w.importPart('Wall bracket '+i,[path.join(samples,'27980400_wall_mount_rev_A.STL')]);
  w.backup(path.join(tmp,'backup'));w.db.close();
  fs.mkdirSync(path.join(tmp,'PrintChill'));fs.writeFileSync(path.join(tmp,'PrintChill/settings.json'),JSON.stringify({root}));
  const server=spawn(process.execPath,[fileURLToPath(new URL('./server.mjs',import.meta.url))],{env:{...process.env,PRC_PORT:'47842',LOCALAPPDATA:tmp},windowsHide:true});
  let browser;
  t.after(async()=>{await browser?.close();const end=once(server,'exit');server.kill();await end;fs.rmSync(tmp,{recursive:true,force:true});});
  await once(server.stdout,'data');
  browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage();page.setDefaultTimeout(10000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const capture=async name=>{
    if(!process.env.PRC_SCREENSHOTS)return;
    fs.mkdirSync(process.env.PRC_SCREENSHOTS,{recursive:true});
    await page.screenshot({path:path.join(process.env.PRC_SCREENSHOTS,name+'.png'),fullPage:true});
  };
  await page.goto('http://127.0.0.1:47842');
  const card=page.locator('.card').filter({hasText:'Wall mount'});
  await card.filter({hasText:/min · [\d.]+ g/}).waitFor({timeout:120000});
  assert.doesNotMatch(await card.innerText(),/Bambu calculation/);
  await page.locator('#side-tags button').click();assert.equal(await page.locator('.card').count(),1);
  await page.locator('#search').fill('wall');
  await capture('01-library');
  await page.waitForSelector('.card img[src^="data:"]');
  await card.scrollIntoViewIfNeeded();
  await card.hover();await card.locator('.dim').filter({hasText:/mm/}).waitFor();
  await page.mouse.move(0,0);await card.focus();assert.ok(await card.locator('.peek').isVisible());
  await card.evaluate(el=>el.addEventListener('click',()=>{el.ownerDocument.body.dataset.testScroll=String(scrollY);},{capture:true,once:true}));
  await card.locator('.visual').click();
  await page.locator('#scene canvas').waitFor();
  await page.getByRole('button',{name:'Dimensions'}).click();
  assert.equal(await page.getByRole('button',{name:'Dimensions'}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Right view'}).click();
  await page.getByRole('button',{name:'Left view'}).click();
  assert.match(await page.locator('[data-dimensions]').innerText(),/mm/);
  await page.getByText('Print details · 3MF A').click();
  assert.match(await page.locator('dl').first().innerText(),/#DCF478/);
  assert.match(await page.locator('dl').first().innerText(),/Bambu calculation/);
  await page.locator('.plates img').first().waitFor();
  assert.ok(await page.locator('.plates img').first().evaluate(img=>img.complete&&img.naturalWidth>0));
  await capture('02-part-with-plates');
  await page.getByRole('button',{name:'Add print report'}).click();
  await page.locator('#measurements').fill('Bore expected 20 mm, measured 19.8 mm, deviation -0.2 mm');
  await page.locator('#notes').fill('Report draft');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Add print report'}).click();
  assert.equal(await page.locator('#notes').inputValue(),'Report draft');
  await page.locator('#param-search').fill('filament_density');
  await page.locator('#param-choice').selectOption('filament_density');
  await page.locator('#param-add').click();
  await page.locator('#report-params').getByText('filament density',{exact:true}).waitFor();
  await page.locator('#report-images').setInputFiles({name:'sample.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a6LsAAAAASUVORK5CYII=','base64')});
  await page.locator('#report-gallery img').waitFor();
  await capture('03-report-draft');
  await page.locator('#submit').click();
  await page.locator('#dialog').waitFor({state:'hidden'});
  await page.getByText(/Print report #/).click();
  await page.locator('#detail').getByText(/Bore expected 20 mm/).waitFor();
  await page.getByRole('button',{name:'← Library'}).click();assert.equal(await page.locator('#search').inputValue(),'wall');
  const [scroll,restored]=await page.evaluate(()=>[Number(document.body.dataset.testScroll),scrollY]);assert.ok(scroll>0);assert.ok(Math.abs(restored-scroll)<2,`Scroll before ${scroll}, restored ${restored}`);assert.ok(await card.evaluate(el=>el===document.activeElement));
  await page.getByText('Filters & saved searches').click();
  await page.locator('#attribute').selectOption('layer_height');
  await page.locator('#attribute-value').fill('9.9');assert.equal(await page.locator('.card').count(),0);
  await page.locator('#attribute-value').fill('0.2');assert.equal(await page.locator('.card').count(),1);
  await page.locator('#save-search').click();await page.locator('#search-name').fill('My mounts');await page.locator('#submit').click();
  await page.waitForFunction(()=>document.querySelector('#saved').textContent.includes('My mounts'));
  await capture('04-search-filters');
  await page.reload();
  await page.getByText('Filters & saved searches').click();
  await page.locator('#saved').selectOption('My mounts');
  assert.equal(await page.locator('#search').inputValue(),'wall');
  assert.equal(await page.locator('#attribute').inputValue(),'layer_height');
  assert.equal(await page.locator('#attribute-value').inputValue(),'0.2');
  await page.locator('#settings').click();await page.getByRole('button',{name:'Restore backup'}).click();
  await page.locator('#src').fill(path.join(tmp,'backup'));await page.locator('#submit').click();
  await page.getByText('Review backup',{exact:true}).waitFor();
  await capture('05-backup-preview');
  await page.getByRole('button',{name:'Confirm merge'}).click();await page.locator('#dialog').waitFor({state:'hidden'});
  assert.deepEqual(errors,[]);
});
